BASE_FMT = 0xEFC74          # "/sdcard/Com2uS/%s/%s"
DD_FMT = 0xED698            # "/data/data/%s/%s"
BASE_POOL = 0xC0B38         # the pool word that selects type 3's format
APP_DIR = '/data/data/'     # what the Java "/sdcard/Com2uS/" constant becomes

ONCREATE = ('    invoke-super {p0, p1}, Landroid/app/Activity;->onCreate'
            '(Landroid/os/Bundle;)V\n')

