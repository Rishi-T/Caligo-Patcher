"""Carry the game's resource folder inside the APK instead of asking the user to
copy it onto the device.

Stock layout, built by the engine at startup:

    /sdcard/Com2uS/com.com2us.caligo/resources.csr      the resource package
    /sdcard/Com2uS/com.com2us.caligo/SE/*.wav           67 sound effects

Every path the engine uses comes from one function, `File::GetFullPathName`
(0xC09C4), which selects a format string from a six-entry jump table and prints
into the caller's buffer:

    type 3  "/sdcard/Com2uS/%s/%s"  @ 0xEFC74   external base  (package, name)
    type 5  "/data/data/%s/%s"      @ 0xED698   app private    (package, name)
    0,2,4   .../lib/lib%s.so, .../lib/%s/lib%s.so               per-file overrides

Both formats take the same two varargs, so pointing type 3's literal-pool word
(0xC0B38) at the /data/data string moves every external-base path into the app's
own sandbox - one 32-bit word, no new code. The literal is a *GOT-relative
offset* (w = target - 0x102A38), which is how this binary addresses .rodata; an
absolute address would be wrong under the loader's arbitrary base.

Java builds the sound-effect path itself - "/sdcard/Com2uS/" + packageName +
"/SE/" + name - so the three constants in SoundManager become "/data/data/".

`BundledData.ensure()` then unpacks assets/bundle/ into the app data directory
on first launch (resources.csr written last, so its presence means "done").
"""

import os
import shutil

from caligo import elfx
from caligo.smali import StageError

