def native_paths(ctx):
    """Point type 3 of GetFullPathName's jump table at /data/data/%s/%s."""
    lib = ctx.lib
    elfx.check(lib, BASE_FMT, b'/sdcard/Com2uS/%s/%s\x00', 'external base format string')
    elfx.check(lib, DD_FMT, b'/data/data/%s/%s\x00', 'app-private format string')
    elfx.check(lib, BASE_POOL, elfx.u32((BASE_FMT - GOT) & 0xFFFFFFFF),
               'type-3 format literal (GOT-relative)')
    elfx.put(lib, BASE_POOL, elfx.u32((DD_FMT - GOT) & 0xFFFFFFFF))
    ctx.note('paths: File::GetFullPathName type 3 -> "/data/data/%%s/%%s" '
             '(0x%X: 0x%08X -> 0x%08X)' % (BASE_POOL, (BASE_FMT - GOT) & 0xFFFFFFFF,
                                           (DD_FMT - GOT) & 0xFFFFFFFF))


def java_paths(ctx):
    tree = ctx.tree
    tree.patch(SND, 'const-string v10, "/sdcard/Com2uS/"',
               'const-string v10, "%s"' % APP_DIR)
    tree.patch(SND, 'const-string v5, "/sdcard/Com2uS/"',
               'const-string v5, "%s"' % APP_DIR, count=2)
    tree.patch(ACT, ONCREATE,
               ONCREATE + '\n    # unpack assets/bundle/ before the engine starts\n'
               '    invoke-static {p0}, Lcom/com2us/caligo/BundledData;->ensure'
               '(Landroid/content/Context;)V\n')
    ctx.note('java: 3 sound paths -> %s<pkg>/SE/, extraction hook in onCreate' % APP_DIR)


def write_assets(ctx, bundle):
    tree = ctx.tree
    src_dir = bundle['dir']
    csr = os.path.join(src_dir, 'resources.csr')
    se = os.path.join(src_dir, 'SE')

    dest = tree.path('assets/bundle/resources.csr')
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    shutil.copyfile(csr, dest)

    names = sorted(n for n in os.listdir(se) if n.lower().endswith('.wav'))
    for name in names:
        dst = tree.path('assets/bundle/SE/' + name)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(os.path.join(se, name), dst)
    tree.write(NEW_CLASS, SMALI)
    ctx.note('assets: bundle/resources.csr (%s) + bundle/SE (%d wavs)'
             % (_mb(os.path.getsize(csr)), len(names)))


def apply(ctx):
    bundle = getattr(ctx, 'bundle', None)
    if not bundle:
        ctx.note('game data: not bundled - copy the folder to the device yourself '
                 '(stock behaviour)')
        return
    native_paths(ctx)
    java_paths(ctx)
    write_assets(ctx, bundle)


def _mb(n):
    return '%.1f MB' % (n / (1024.0 * 1024.0))
